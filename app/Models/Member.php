<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\SoftDeletes;

class Member extends Model
{
    use HasFactory, SoftDeletes;

    protected $table = 'members';

    protected $fillable = [
        'member_code',
        'name',
        'email',
        'phone',
        'status',
        'joined_at',
    ];

    protected $casts = [
        'joined_at' => 'datetime',
    ];

    /**
     * Relationships where this member is the parent (upline).
     */
    public function childRelationships(): HasMany
    {
        return $this->hasMany(MemberRelationship::class, 'parent_member_id');
    }

    /**
     * Direct children members.
     */
    public function directChildren(): BelongsToMany
    {
        return $this->belongsToMany(Member::class, 'member_relationships', 'parent_member_id', 'child_member_id')
            ->withPivot(['override_rate', 'commission_model_id', 'status', 'effective_from', 'effective_to'])
            ->withTimestamps();
    }

    /**
     * Relationships where this member is the child (downline).
     */
    public function parentRelationships(): HasMany
    {
        return $this->hasMany(MemberRelationship::class, 'child_member_id');
    }

    /**
     * Direct parent members.
     */
    public function directParents(): BelongsToMany
    {
        return $this->belongsToMany(Member::class, 'member_relationships', 'child_member_id', 'parent_member_id')
            ->withPivot(['override_rate', 'commission_model_id', 'status', 'effective_from', 'effective_to'])
            ->withTimestamps();
    }

    /**
     * Personal sales transactions originated by this member.
     */
    public function salesTransactions(): HasMany
    {
        return $this->hasMany(SalesTransaction::class, 'member_id');
    }

    /**
     * Commission ledger entries where this member was the earner/beneficiary.
     */
    public function earnedCommissions(): HasMany
    {
        return $this->hasMany(CommissionLedgerEntry::class, 'beneficiary_member_id');
    }

    /**
     * Commission ledger entries generated by this member's sales.
     */
    public function originatedCommissions(): HasMany
    {
        return $this->hasMany(CommissionLedgerEntry::class, 'seller_member_id');
    }

    /**
     * Scope for active members.
     */
    public function scopeActive($query)
    {
        return $query->where('status', 'active');
    }
}
